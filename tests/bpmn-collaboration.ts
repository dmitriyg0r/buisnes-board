import { blankXml } from '../src/bpmn';
import { bpmnNotation } from '../src/modeling/bpmn';
import { addBlackBoxParticipant, addMessageFlow, convertToCollaboration, inspectCollaboration, moveBlackBoxParticipant, removeCollaborationElement } from '../src/modeling/bpmnCollaboration';

function assert(value: unknown, message: string): asserts value { if (!value) throw new Error(message); }
function fails(fn: () => unknown) { let thrown = false; try { fn(); } catch { thrown = true; } assert(thrown, 'Ожидался отказ'); }
export function runCollaborationTests() {
  let xml = blankXml('Проверка');
  xml = bpmnNotation.addRegion!(xml, { x: 120, y: 120 });
  xml = bpmnNotation.addNode(xml, 'task', { x: 350, y: 150 });
  const initial = bpmnNotation.read(xml).diagram;
  xml = bpmnNotation.connect(xml, initial.nodes[0].id, initial.nodes[1].id);
  const before = new DOMParser().parseFromString(xml, 'application/xml');
  const model = 'http://www.omg.org/spec/BPMN/20100524/MODEL';
  const di = 'http://www.omg.org/spec/BPMN/20100524/DI';
  const process = before.getElementsByTagNameNS(model, 'process')[0];
  const oldShapes = Array.from(before.getElementsByTagNameNS(di, 'BPMNShape')).map(s => new XMLSerializer().serializeToString(s));
  xml = convertToCollaboration(xml);
  const outputs = [xml];
  let parsed = new DOMParser().parseFromString(xml, 'application/xml');
  assert(new XMLSerializer().serializeToString(parsed.getElementsByTagNameNS(model, 'process')[0]) === new XMLSerializer().serializeToString(process), 'Процесс или дорожки изменились');
  for (const shape of oldShapes) assert(Array.from(parsed.getElementsByTagNameNS(di, 'BPMNShape')).some(s => new XMLSerializer().serializeToString(s) === shape), 'DI изменён');
  assert(bpmnNotation.read(xml).readOnlyReason, 'Старый адаптер должен запретить редактирование collaboration');
  let state = inspectCollaboration(xml); assert(state.editable && state.participants.length === 1, 'Конверсия не прочитана');
  const main = state.participants[0];
  xml = addBlackBoxParticipant(xml, 'Внешний участник', { x: main.bounds.x, y: main.bounds.y + main.bounds.height + 100, width: 400, height: 100 });
  outputs.push(xml);
  state = inspectCollaboration(xml); const other = state.participants.find(p => !p.processRef)!;
  const start = { x: main.bounds.x + 50, y: main.bounds.y + main.bounds.height }, end = { x: other.bounds.x + 50, y: other.bounds.y };
  fails(() => addMessageFlow(xml, main.id, main.id, [start, end]));
  fails(() => addMessageFlow(xml, main.id, other.id, [{ x: 0, y: 0 }, end]));
  fails(() => addMessageFlow(xml, 'StartEvent_1', other.id, [start, end]));
  xml = addMessageFlow(xml, main.id, other.id, [start, { x: start.x, y: start.y + 50 }, end], 'Запрос');
  outputs.push(xml);
  state = inspectCollaboration(xml); assert(state.editable && state.messageFlows.length === 1, 'Поток не прочитан');
  const flow = state.messageFlows[0]; fails(() => removeCollaborationElement(xml, other.id));
  fails(() => moveBlackBoxParticipant(xml, other.id, { x: other.bounds.x + 10, y: other.bounds.y + 20 }));
  fails(() => addMessageFlow(xml, main.id, other.id, [start, { x: start.x, y: main.bounds.y + 1 }, end]));
  fails(() => addMessageFlow(xml, main.id, other.id, [start, { x: end.x, y: other.bounds.y + 1 }, end]));
  assert(!inspectCollaboration(xml.replace('isHorizontal="true"', 'isHorizontal="0"')).editable, 'Вертикальный пул недопустим');
  assert(!inspectCollaboration(xml.replace('isExecutable="false"', 'isExecutable="bogus"')).editable, 'Некорректный Boolean');
  fails(() => moveBlackBoxParticipant(xml, main.id, { x: 0, y: 0 }));
  const unknown = xml.replace('<bpmn:participant ', '<bpmn:participant custom="данные" ');
  assert(!inspectCollaboration(unknown).editable, 'Неизвестные атрибуты разрешены'); fails(() => removeCollaborationElement(unknown, flow.id));
  parsed = new DOMParser().parseFromString(xml, 'application/xml');
  const snapshot = new XMLSerializer().serializeToString(parsed);
  assert(inspectCollaboration(snapshot).editable, 'Повторное чтение не удалось');
  const validatedXml = xml;
  xml = removeCollaborationElement(xml, flow.id); outputs.push(xml);
  xml = moveBlackBoxParticipant(xml, other.id, { x: other.bounds.x + 10, y: other.bounds.y + 20 });
  outputs.push(xml);
  assert(inspectCollaboration(xml).participants.find(p => p.id === other.id)?.bounds.x === other.bounds.x + 10, 'Пул не перемещён');
  xml = removeCollaborationElement(xml, other.id); outputs.push(xml);
  assert(inspectCollaboration(xml).participants.length === 1 && inspectCollaboration(xml).messageFlows.length === 0, 'Удаление не завершено');
  assert(new XMLSerializer().serializeToString(new DOMParser().parseFromString(xml, 'application/xml').getElementsByTagNameNS(model, 'process')[0]) === new XMLSerializer().serializeToString(process), 'Удаление повредило процесс');
  fails(() => removeCollaborationElement(xml, main.id));
  xml = addBlackBoxParticipant(xml, 'Повторный участник', other.bounds);
  state = inspectCollaboration(xml);
  const replacement = state.participants.find(p => !p.processRef)!;
  assert(replacement.id !== other.id, 'ID удалённого участника использован повторно');
  xml = addMessageFlow(xml, main.id, replacement.id, [start, end]);
  const replacementFlow = inspectCollaboration(xml).messageFlows[0];
  assert(replacementFlow.id !== flow.id, 'ID удалённого потока использован повторно');
  outputs.push(xml);
  const emptyProcess = bpmnNotation.remove(blankXml('Пустой процесс'), 'StartEvent_1');
  const emptyCollaboration = convertToCollaboration(emptyProcess);
  const emptyMain = inspectCollaboration(emptyCollaboration).participants[0];
  const withoutPool = removeCollaborationElement(emptyCollaboration, emptyMain.id);
  const withoutPoolDoc = new DOMParser().parseFromString(withoutPool, 'application/xml');
  assert(!bpmnNotation.read(withoutPool).readOnlyReason, 'Пустой процесс после удаления пула должен редактироваться');
  assert(withoutPoolDoc.getElementsByTagNameNS(model, 'process')[0]?.id === 'Process_1', 'ID процесса должен сохраниться');
  assert(withoutPoolDoc.getElementsByTagNameNS(model, 'participant').length === 0 && withoutPoolDoc.getElementsByTagNameNS(model, 'collaboration').length === 0, 'Пул и пустая collaboration не удалены');
  assert(withoutPoolDoc.getElementsByTagNameNS(di, 'BPMNPlane')[0]?.getAttribute('bpmnElement') === 'Process_1', 'Плоскость должна ссылаться на процесс');
  const withExternal = addBlackBoxParticipant(emptyCollaboration, 'Внешний', { x: 1000, y: 1000, width: 400, height: 120 });
  fails(() => removeCollaborationElement(withExternal, emptyMain.id));
  const namedCollaboration = emptyCollaboration.replace('<bpmn:collaboration ', '<bpmn:collaboration name="Совместная работа" ');
  fails(() => removeCollaborationElement(namedCollaboration, emptyMain.id));
  outputs.push(withoutPool);
  return { validatedXml, outputs, status: 'passed' };
}
