import assert from 'node:assert/strict';
import { epcNotation, epcSymbols } from '../src/modeling/epc';
import { nodeLabelBounds, labelLines } from '../src/modeling/DiagramEditor';
import type { DiagramNode, DiagramSymbol } from '../src/modeling/types';

assert.ok(epcSymbols.every(symbol => symbol.appearance?.fill && symbol.appearance.stroke));
assert.notEqual(epcSymbols.find(s => s.type === 'event')!.appearance!.fill, epcSymbols.find(s => s.type === 'function')!.appearance!.fill);
assert.notEqual(epcSymbols.find(s => s.type === 'internal-employee')!.shape, 'actor');
let source = epcNotation.createEmpty();
source = epcNotation.addNode(source, 'function', { x: 20, y: 40 });
let node = epcNotation.read(source).diagram.nodes[0];
assert.equal(node.label, 'Функция');
source = epcNotation.rename(source, node.id, 'Моё название');
assert.equal(epcNotation.read(source).diagram.nodes[0].label, 'Моё название');
source = epcNotation.rename(source, node.id, '');
assert.equal(epcNotation.read(source).diagram.nodes[0].label, '');
const symbol = epcSymbols.find(s => s.type === 'function')!;
node = { ...node, labelBounds: { x: 100, y: 200, width: 80, height: 30 } };
assert.deepEqual(nodeLabelBounds(node, symbol), node.labelBounds);
const base: DiagramNode = { id: 'x', type: 'x', label: 'Имя', x: 10, y: 20, width: 100, height: 60 };
const rect: DiagramSymbol = { type: 'x', title: 'x', shape: 'rounded-rectangle', width: 100, height: 60 };
const bounds = nodeLabelBounds(base, rect);
assert.equal(bounds.y + bounds.height / 2, base.y + base.height / 2);
const small = nodeLabelBounds(base, { ...rect, shape: 'circle' });
assert.ok(small.y >= base.y + base.height);
const annotation = nodeLabelBounds(base, { ...rect, shape: 'annotation' });
assert.equal(annotation.x, base.x + 12);
assert.ok(labelLines('Слишком длинная подпись для маленького объекта', 30, 1)[0].endsWith('…'));
console.log('EPC: оформление, подписи, сохранение имён и положения текста — OK');
