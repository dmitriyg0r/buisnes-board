import { strict as assert } from 'node:assert';
import { parseSequence, umlSequenceNotation as seq } from '../src/modeling/umlSequence';

const timeline = seq.timeline;
let base = seq.createEmpty();
for (const x of [0, 300, 600]) base = seq.addNode(base, 'lifeline', { x, y: 0 });
const [caller, worker, other] = parseSequence(base).lifelines.map(line => line.id);
let source = timeline.addMessage(base, caller, worker, 140, 'create');
const birth = parseSequence(source).messages[0];
assert.equal(birth.kind, 'create');
assert.deepEqual(timeline.project(source).messages[0].points.at(-1), { x: 300, y: 140 });
assert.equal(seq.read(source).diagram.nodes.find(n => n.id === worker)?.y, 115);
assert.equal(timeline.project(source).lifelines.find(line => line.id === worker)?.lineStart.y, 165);
assert.throws(() => timeline.addMessage(source, caller, worker, 220, 'create'), /одного|один/);
assert.throws(() => timeline.addMessage(source, worker, other, 156, 'sync'), /вне линии жизни/);
assert.throws(() => timeline.addExecution(source, worker, 156), /прежде|после|диапазон/);
source = timeline.addMessage(source, worker, other, 205, 'sync');
source = timeline.addExecution(source, worker, 205, 234);
source = timeline.addMessage(source, caller, worker, 240, 'delete');
const death = parseSequence(source).messages.at(-1)!;
assert.deepEqual(timeline.project(source).lifelines.find(line => line.id === worker)?.destruction, { x: 370, y: 240 });
assert.deepEqual(timeline.project(source).messages.at(-1)?.points.at(-1), { x: 370, y: 240 });
assert.throws(() => timeline.addMessage(source, worker, other, 255), /вне линии жизни/);
assert.throws(() => timeline.addExecution(source, worker, 218, 246), /после|диапазон/);
assert.throws(() => timeline.moveMessage(source, death.id, 212, 212), /после|диапазон/);
assert.throws(() => timeline.moveMessage(source, birth.id, 200, 200), /вне линии жизни/);
const moved = timeline.moveMessage(source, death.id, 256, 256);
assert.equal(timeline.project(moved).lifelines.find(line => line.id === worker)?.lineEnd.y, 256);
const shifted = seq.moveNode(moved, worker, { x: 340, y: 115 });
assert.equal(timeline.project(shifted).messages[0].points.at(-1)?.x, 340);
assert.equal(parseSequence(shifted).messages[0].id, birth.id);
const reopened = JSON.stringify(parseSequence(shifted));
assert.deepEqual(timeline.project(reopened), timeline.project(shifted));
const withoutDeath = seq.remove(reopened, death.id);
assert.equal(timeline.project(withoutDeath).lifelines.find(line => line.id === worker)?.lineEnd.y, 450);
const withoutBirth = seq.remove(withoutDeath, birth.id);
assert.equal(seq.read(withoutBirth).diagram.nodes.find(n => n.id === worker)?.y, 0);
assert.deepEqual(parseSequence(withoutBirth).lifelines.find(line => line.id === worker), { ...parseSequence(base).lifelines[1], x: 340 });
assert.equal(parseSequence(timeline.editMessage!(reopened, death.id, { kind: 'sync' })).messages.at(-1)?.id, death.id);
console.log('UML Sequence: создание и уничтожение участника, ограничения времени, перемещение и переоткрытие — OK');
