import { strict as assert } from 'node:assert';
import { addSequenceLifeline, addSequenceMessage, createSequence, editSequenceMessage, moveSequenceLifeline, moveSequenceMessage, parseSequence, projectSequence, removeSequenceElement, renameSequenceElement, resizeSequenceLifeline, serializeSequence, umlSequenceNotation } from '../src/modeling/umlSequence';

let source = createSequence();
source = addSequenceLifeline(source, { x: 300, y: 20 });
source = addSequenceLifeline(source, { x: 50, y: 20 });
let doc = parseSequence(source);
assert.deepEqual(doc.lifelines.map(line => line.x), [50, 300]);
assert.notEqual(doc.lifelines[0].id, doc.lifelines[1].id);
const [a, b] = doc.lifelines.map(line => line.id);
source = addSequenceMessage(source, { label: 'запрос', kind: 'sync', send: { lifelineId: a, y: 110 }, receive: { lifelineId: b, y: 110 } });
source = addSequenceMessage(source, { label: 'ответ', kind: 'reply', send: { lifelineId: b, y: 210 }, receive: { lifelineId: a, y: 210 } });
source = addSequenceMessage(source, { label: 'себе', kind: 'self', send: { lifelineId: a, y: 150 }, receive: { lifelineId: a, y: 180 } });
source = addSequenceMessage(source, { label: 'событие', kind: 'async', send: { lifelineId: a, y: 250 }, receive: { lifelineId: b, y: 250 } });
doc = parseSequence(source);
assert.deepEqual(doc.messages.map(message => message.kind), ['sync', 'self', 'reply', 'async']);
assert.deepEqual(parseSequence(serializeSequence(doc)), doc);
const projection = projectSequence(doc);
assert.equal(projection.lifelines[0].lineStart.y, 70);
assert.equal(projection.messages[0].points[0].x, 120);
assert.equal(projection.messages[1].points.length, 4);
assert.equal(projection.messages[2].lineStyle, 'dashed');
assert.equal(projection.messages[3].arrowStyle, 'open');
source = moveSequenceMessage(source, doc.messages[0].id, 220, 220);
assert.deepEqual(parseSequence(source).messages.map(message => message.kind), ['self', 'reply', 'sync', 'async']);
source = moveSequenceLifeline(source, a, { x: 500, y: 20 });
assert.deepEqual(parseSequence(source).lifelines.map(line => line.id), [b, a]);
assert.equal(projectSequence(parseSequence(source)).messages[0].points[0].x, 570);
source = renameSequenceElement(source, a, 'Клиент');
assert.equal(parseSequence(source).lifelines[1].label, 'Клиент');
assert.equal(umlSequenceNotation.read(source).diagram.edges.length, 0);
assert.equal(umlSequenceNotation.read(source).readOnlyReason, undefined);
assert.deepEqual(parseSequence(umlSequenceNotation.createEmpty()).lifelines, []);
assert.throws(() => umlSequenceNotation.connect(source, a, b));
assert.throws(() => addSequenceMessage(source, { label: '', kind: 'sync', send: { lifelineId: a, y: 90 }, receive: { lifelineId: a, y: 90 } }));
assert.throws(() => addSequenceMessage(source, { label: '', kind: 'self', send: { lifelineId: a, y: 90 }, receive: { lifelineId: a, y: 90 } }));
assert.throws(() => addSequenceMessage(source, { label: '', kind: 'async', send: { lifelineId: a, y: 90 }, receive: { lifelineId: 'missing', y: 90 } }));
assert.throws(() => moveSequenceMessage(source, parseSequence(source).messages[0].id, 30, 40));
assert.throws(() => parseSequence(JSON.stringify({ ...parseSequence(source), version: 2 })));
assert.throws(() => parseSequence(JSON.stringify({ ...parseSequence(source), extension: true })));
const invalid = parseSequence(source); invalid.messages[0].id = invalid.lifelines[0].id;
assert.throws(() => serializeSequence(invalid));
// Изменение свойств атомарно и не теряет остальные элементы модели.
const original = parseSequence(source);
const message = original.messages.find(item => item.kind === 'async')!;
const edited = editSequenceMessage(source, message.id, { kind: 'reply', label: 'готово' });
assert.equal(parseSequence(edited).messages.find(item => item.id === message.id)?.kind, 'reply');
assert.equal(projectSequence(parseSequence(edited)).messages.find(item => item.id === message.id)?.lineStyle, 'dashed');
assert.deepEqual(parseSequence(edited).lifelines, original.lifelines);
assert.throws(() => editSequenceMessage(source, message.id, { kind: 'self' }));
assert.throws(() => editSequenceMessage(source, message.id, { receive: { lifelineId: 'нет', y: 250 } }));
assert.deepEqual(parseSequence(source), original);
const resized = resizeSequenceLifeline(source, a, 180, 60);
assert.equal(parseSequence(resized).lifelines.find(line => line.id === a)?.width, 180);
assert.deepEqual(parseSequence(resized).messages, original.messages);
assert.throws(() => resizeSequenceLifeline(source, a, 140, 200), /перекрывать/);
assert.throws(() => resizeSequenceLifeline(source, a, NaN, 50));
assert.ok(umlSequenceNotation.resizeNode);
const shifted = moveSequenceLifeline(source, a, { x: 500, y: -200 });
assert.deepEqual(parseSequence(shifted).messages, original.messages);
assert.ok(parseSequence(shifted).lifelines.find(line => line.id === a)!.endY >= 250);
assert.throws(() => moveSequenceLifeline(source, a, { x: 500, y: 150 }), /ниже/);
const timeline = umlSequenceNotation.timeline!;
const changedType = timeline.editMessage!(source, message.id, { kind: 'reply' });
assert.equal(timeline.project(changedType).messages.find(item => item.id === message.id)?.kind, 'reply');
assert.throws(() => timeline.editMessage!(source, message.id, { to: a }));
const syncMessage = timeline.editMessage!(source, message.id, { kind: 'sync' });
const changedEndpoint = timeline.editMessage!(syncMessage, message.id, { to: a });
assert.equal(timeline.project(changedEndpoint).messages.find(item => item.id === message.id)?.kind, 'self');
assert.throws(() => timeline.editMessage!(changedEndpoint, message.id, { kind: 'async' }));
const restoredEndpoint = timeline.editMessage!(changedEndpoint, message.id, { to: b });
assert.equal(timeline.project(restoredEndpoint).messages.find(item => item.id === message.id)?.kind, 'sync');
assert.throws(() => timeline.addMessage(source, a, b, 100, 'unknown'), /Неизвестный/);
assert.throws(() => timeline.addMessage(source, a, a, 100, 'reply'), /только как синхронный/);
assert.equal(parseSequence(timeline.addMessage(source, a, a, 100, 'sync')).messages.find(item => item.send.y === 100)?.kind, 'self');
const extended = timeline.addMessage(source, a, b, 900, 'sync');
assert.ok(parseSequence(extended).lifelines.every(line => line.endY >= 900));
const late = parseSequence(extended).messages.at(-1)!;
assert.ok(parseSequence(moveSequenceMessage(extended, late.id, 1500, 1500)).lifelines.every(line => line.endY >= 1500));
assert.ok(parseSequence(timeline.addMessage(extended, a, a, 1700, 'sync')).lifelines.find(line => line.id === a)!.endY >= 1730);
const imported = parseSequence(extended); imported.lifelines[0].endY = 300;
assert.throws(() => parseSequence(JSON.stringify(imported)), /вне линии жизни/);
assert.deepEqual(parseSequence(source), original);
source = removeSequenceElement(source, a);
assert.equal(parseSequence(source).messages.length, 0);
assert.equal(parseSequence(source).lifelines.length, 1);
console.log('UML Sequence: проверки пройдены');
