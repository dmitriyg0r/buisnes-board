import { blankXml } from '../src/bpmn';
import { endpointsFaceOutward, routeBetweenNodes } from '../src/modeling/diagramRouting';
import { bpmnNotation as notation } from '../src/modeling/bpmn';
import type { DiagramNode, DiagramPoint } from '../src/modeling/types';

const result = document.querySelector<HTMLElement>('#result')!;
const assert = (value: unknown, message: string) => { if (!value) throw new Error(message); };
function crosses(a: DiagramPoint, b: DiagramPoint, n: DiagramNode) {
  if (a.x === b.x) return a.x > n.x && a.x < n.x + n.width && Math.max(a.y, b.y) > n.y && Math.min(a.y, b.y) < n.y + n.height;
  if (a.y === b.y) return a.y > n.y && a.y < n.y + n.height && Math.max(a.x, b.x) > n.x && Math.min(a.x, b.x) < n.x + n.width;
  return true;
}
function clear(points: DiagramPoint[], n: DiagramNode) { return points.slice(1).every((p, i) => !crosses(points[i], p, n)); }
try {
  let xml = notation.addNode(blankXml('Маршруты'), 'task', { x: 600, y: 140 });
  xml = notation.addNode(xml, 'task', { x: 350, y: 140 });
  const nodes = notation.read(xml).diagram.nodes;
  const start = nodes.find(n => n.type === 'startEvent')!, target = nodes.find(n => n.type === 'task' && n.x === 600)!, blocker = nodes.find(n => n.type === 'task' && n.x === 350)!;
  xml = notation.connect(xml, start.id, target.id);
  let edge = notation.read(xml).diagram.edges[0];
  const initialStart = edge.points[0], initialEnd = edge.points[edge.points.length - 1];
  assert(clear(edge.points, blocker), 'Новая связь проходит через постороннюю задачу');
  xml = notation.moveNode(xml, target.id, { x: 600, y: 400 });
  edge = notation.read(xml).diagram.edges[0];
  assert(JSON.stringify(edge.points[0]) === JSON.stringify(initialStart) && edge.points.at(-1)!.x === initialEnd.x && edge.points.at(-1)!.y === initialEnd.y + 260, 'При перемещении изменились точки привязки');
  assert(clear(edge.points, blocker), 'Связь после перемещения проходит через постороннюю задачу');
  assert(edge.points.slice(1).every((p, i) => p.x === edge.points[i].x || p.y === edge.points[i].y), 'После перемещения появилась диагональ');
  const originalId = edge.id;
  let swappedXml = notation.addNode(blankXml('Перемещение'), 'task', { x: 400, y: 140 });
  const swappedNodes = notation.read(swappedXml).diagram.nodes;
  const swappedStart = swappedNodes.find(n => n.type === 'startEvent')!, swappedTarget = swappedNodes.find(n => n.type === 'task')!;
  swappedXml = notation.connect(swappedXml, swappedStart.id, swappedTarget.id);
  const swappedBefore = notation.read(swappedXml).diagram.edges[0].points;
  swappedXml = notation.moveNode(swappedXml, swappedTarget.id, { x: 20, y: 140 });
  const swapped = notation.read(swappedXml).diagram;
  assert(endpointsFaceOutward(swapped.edges[0].points, swapped.nodes.find(n => n.id === swappedStart.id)!, swapped.nodes.find(n => n.id === swappedTarget.id)!), 'При перемещении объекта на другую сторону стрелка развернулась внутрь');
  assert(JSON.stringify(swapped.edges[0].points[0]) === JSON.stringify(swappedBefore[0]) && swapped.edges[0].points.at(-1)!.x === swappedBefore.at(-1)!.x - 380 && swapped.edges[0].points.at(-1)!.y === swappedBefore.at(-1)!.y, 'При переносе на другую сторону изменились точки привязки');
  xml = notation.resetEdge(xml, edge.id);
  edge = notation.read(xml).diagram.edges.find(e => e.id === originalId)!;
  assert(clear(edge.points, blocker), 'Сброс прошёл через препятствие');
  xml = notation.resizeNode!(xml, target.id, 140, 100);
  edge = notation.read(xml).diagram.edges.find(e => e.id === originalId)!;
  assert(edge && clear(edge.points, blocker), 'Изменение размера нарушило маршрут или ID');
  xml = notation.addNode(xml, 'dataObjectReference', { x: 130, y: 400 });
  const data = notation.read(xml).diagram.nodes.find(n => n.type === 'dataObjectReference')!;
  xml = notation.connect(xml, data.id, target.id, 'dataInputAssociation');
  const dataEdge = notation.read(xml).diagram.edges.find(e => e.type === 'dataInputAssociation')!;
  assert(dataEdge && clear(dataEdge.points, blocker), 'Ассоциация данных проходит через препятствие');
  xml = notation.resetEdge(xml, dataEdge.id);
  assert(notation.read(xml).diagram.edges.some(e => e.id === dataEdge.id), 'Сброс потерял ID ассоциации данных');
  const current = notation.read(xml).diagram.nodes;
  const a = current.find(n => n.id === data.id)!, b = current.find(n => n.id === target.id)!;
  const explicitStart = { x: a.x + a.width, y: a.y + a.height / 2 };
  const explicitEnd = { x: b.x, y: b.y + b.height / 2 };
  const direct = routeBetweenNodes(current, a, b, explicitStart, explicitEnd);
  assert(direct && JSON.stringify(direct[0]) === JSON.stringify(explicitStart) && JSON.stringify(direct[direct.length - 1]) === JSON.stringify(explicitEnd), 'Мост потерял выбранные точки');
  const ellipse: DiagramNode = { id: 'ellipse', type: 'startEvent', label: '', x: 0, y: 0, width: 100, height: 100 };
  const other: DiagramNode = { id: 'other', type: 'task', label: '', x: 300, y: 0, width: 100, height: 100 };
  const ellipsePort = { x: 90, y: 20 };
  const curved = routeBetweenNodes([ellipse, other], ellipse, other, ellipsePort);
  assert(curved && curved[0].x === ellipsePort.x && curved[0].y === ellipsePort.y && curved[1].y === ellipsePort.y && curved[1].x > ellipsePort.x, 'Привязка к фактическому краю эллипса потеряна');
  let fixedXml = notation.addNode(blankXml('Привязки'), 'task', { x: 450, y: 300 });
  let fixedDiagram = notation.read(fixedXml).diagram;
  const fixedFrom = fixedDiagram.nodes.find(n => n.type === 'startEvent')!, fixedTo = fixedDiagram.nodes.find(n => n.type === 'task')!;
  fixedXml = notation.connect(fixedXml, fixedFrom.id, fixedTo.id);
  const fixedEdge = notation.read(fixedXml).diagram.edges[0];
  const fixedStart = { x: fixedFrom.x + fixedFrom.width / 2, y: fixedFrom.y + fixedFrom.height }, fixedEnd = { x: fixedTo.x + fixedTo.width / 2, y: fixedTo.y };
  const fixedRoute = routeBetweenNodes(fixedDiagram.nodes, fixedFrom, fixedTo, fixedStart, fixedEnd)!;
  assert(fixedRoute, 'Не создан маршрут с заданными привязками');
  fixedXml = notation.editEdge(fixedXml, fixedEdge.id, fixedFrom.id, fixedTo.id, fixedRoute);
  fixedXml = notation.resetEdge(fixedXml, fixedEdge.id);
  fixedDiagram = notation.read(fixedXml).diagram;
  assert(JSON.stringify(fixedDiagram.edges[0].points[0]) === JSON.stringify(fixedStart) && JSON.stringify(fixedDiagram.edges[0].points.at(-1)) === JSON.stringify(fixedEnd), 'Сброс изменил точки привязки');
  let blockedXml = notation.addNode(blankXml('Защита привязок'), 'task', { x: 500, y: 140 });
  blockedXml = notation.addNode(blockedXml, 'task', { x: 270, y: 400 });
  let blockedDiagram = notation.read(blockedXml).diagram;
  const blockedFrom = blockedDiagram.nodes.find(n => n.type === 'startEvent')!, blockedTo = blockedDiagram.nodes.find(n => n.type === 'task' && n.x === 500)!, blockerToMove = blockedDiagram.nodes.find(n => n.type === 'task' && n.y === 400)!;
  blockedXml = notation.connect(blockedXml, blockedFrom.id, blockedTo.id);
  blockedDiagram = notation.read(blockedXml).diagram;
  const blockedEdge = blockedDiagram.edges[0], movedBlocker = { ...blockerToMove, x: 220, y: 150 };
  const nextNodes = blockedDiagram.nodes.map(n => n.id === movedBlocker.id ? movedBlocker : n);
  assert(routeBetweenNodes(nextNodes, blockedFrom, blockedTo, blockedEdge.points[0], blockedEdge.points.at(-1)) === null && routeBetweenNodes(nextNodes, blockedFrom, blockedTo), 'Не воспроизведена ситуация со сменой точки привязки');
  blockedXml = notation.moveNode(blockedXml, blockerToMove.id, { x: movedBlocker.x, y: movedBlocker.y });
  const blockedAfter = notation.read(blockedXml).diagram;
  assert(blockedAfter.nodes.find(n => n.id === movedBlocker.id)?.x === movedBlocker.x && JSON.stringify(blockedAfter.edges[0].points[0]) === JSON.stringify(blockedEdge.points[0]) && JSON.stringify(blockedAfter.edges[0].points.at(-1)) === JSON.stringify(blockedEdge.points.at(-1)), 'Недоступный маршрут изменил точки привязки или заблокировал перемещение');
  const enclosure = { id: 'enclosure', type: 'task', label: '', x: a.x - 10, y: a.y - 10, width: a.width + 20, height: a.height + 20 };
  assert(routeBetweenNodes([...current, enclosure], a, b) === null, 'Недоступный маршрут должен возвращать null');
  const oldRoute = notation.read(xml).diagram.edges.find(e => e.id === originalId)!;
  const bend = oldRoute.points.length > 2 ? oldRoute.points[1] : null;
  if (bend) {
    const unchanged = notation.moveNode(xml, target.id, { x: b.x, y: b.y });
    assert(JSON.stringify(notation.read(unchanged).diagram.edges.find(e => e.id === originalId)!.points) === JSON.stringify(oldRoute.points), 'Неподвижный ручной маршрут изменился');
  }
  const original = notation.read(xml).diagram.edges.find(e => e.id === originalId)!;
  const diagonal = [original.points[0], original.points[original.points.length - 1]];
  const diagonalXml = notation.editEdge(xml, original.id, original.from, original.to, diagonal);
  const mid = { x: (diagonal[0].x + diagonal[1].x) / 2, y: (diagonal[0].y + diagonal[1].y) / 2 };
  const coveredDiagonal = notation.moveNode(diagonalXml, blocker.id, { x: mid.x - blocker.width / 2, y: mid.y - blocker.height / 2 });
  const afterCover = notation.read(coveredDiagonal).diagram;
  assert(afterCover.nodes.find(n => n.id === blocker.id)?.x === Math.round(mid.x - blocker.width / 2), 'Пересечение диагонали заблокировало перемещение');
  assert(JSON.stringify(afterCover.edges.find(e => e.id === originalId)!.points) === JSON.stringify(diagonal), 'Посторонняя диагональная связь изменилась');
  const movedDiagonal = notation.moveNode(diagonalXml, target.id, { x: b.x + 10, y: b.y + 10 });
  const imported = notation.read(movedDiagonal).diagram.edges.find(e => e.id === originalId)!;
  assert(imported.points.length === 2 && imported.points[0].x !== imported.points[1].x && imported.points[0].y !== imported.points[1].y, 'Импортированная диагональ молча перестроена');
  (window as unknown as { routingXml: string }).routingXml = xml;
  result.textContent = 'Успешно: обход препятствия при создании, перемещении, изменении размера, сбросе и работе с данными.'; result.dataset.status = 'passed';
} catch (error) { result.textContent = `Ошибка: ${error instanceof Error ? error.message : String(error)}`; result.dataset.status = 'failed'; }
