const result = document.querySelector<HTMLElement>('#result')!;
const pause = () => new Promise(resolve => setTimeout(resolve, 150));
const assert = (value: unknown, message: string) => { if (!value) throw new Error(message); };
const frame = document.createElement('iframe'); frame.style.cssText = 'width:1000px;height:700px'; document.body.append(frame);
try {
  frame.src = '/tests/editor.html'; await new Promise<void>(resolve => { frame.onload = () => resolve(); }); await pause();
  const win = frame.contentWindow! as Window & typeof globalThis, doc = win.document;
  const svg = doc.querySelector<SVGSVGElement>('.diagram-surface')!;
  const world = (x: number, y: number) => { const p = svg.createSVGPoint(); p.x = x; p.y = y; return p.matrixTransform(svg.getScreenCTM()!); };
  const send = (el: Element, type: string, p: { x:number;y:number }, button = 0) => el.dispatchEvent(new win.PointerEvent(type, { bubbles: true, button, buttons: type === 'pointerup' ? 0 : button === 1 ? 4 : 1, clientX: p.x, clientY: p.y, pointerId: 7 }));
  const toggle = doc.querySelector<HTMLButtonElement>('[aria-label="Привязка к сетке"]');
  const grid = doc.querySelector<SVGPatternElement>('[data-diagram-grid-pattern]');
  assert(grid && toggle && toggle.getAttribute('aria-pressed') === 'true', 'Нет включенной сетки и переключателя привязки');
  assert(grid!.getAttribute('patternUnits') === 'userSpaceOnUse' && grid!.getAttribute('width') === '8', 'Сетка не привязана к координатам модели');
  const gridToggle = doc.querySelector<HTMLButtonElement>('[aria-label="Сетка"]')!;
  gridToggle.click(); await pause(); assert(!doc.querySelector('[data-diagram-grid]'), 'Сетка не скрывается');
  assert((Array.from(doc.querySelectorAll('button')).find(el => el.textContent === 'Сохранить') as HTMLButtonElement).disabled, 'Настройки сетки изменили модель');
  gridToggle.click(); await pause(); assert(doc.querySelector('[data-diagram-grid]'), 'Сетка не появилась');
  (doc.querySelector('[aria-label="Умные направляющие"]') as HTMLButtonElement).click(); await pause();
  svg.setPointerCapture = () => {}; svg.hasPointerCapture = () => false;
  const task = doc.querySelector<SVGGElement>('[data-diagram-node][aria-label*="Проверить заявку"]')!;
  task.setPointerCapture = () => {}; task.hasPointerCapture = () => false;
  const start = task.transform.baseVal.consolidate()!.matrix;
  const pos = { x: start.e, y: start.f }; const p = world(pos.x + 30, pos.y + 30), end = world(pos.x + 53, pos.y + 49);
  send(task, 'pointerdown', p); send(task, 'pointermove', end); await pause(); send(task, 'pointerup', end); await pause();
  const moved = task.transform.baseVal.consolidate()!.matrix;
  assert(moved.e % 8 === 0 && moved.f % 8 === 0, 'Объект не привязан к сетке при перемещении');
  win.dispatchEvent(new win.KeyboardEvent('keydown', { key: 'z', code: 'KeyZ', metaKey: true, bubbles: true })); await pause();
  const restored = task.transform.baseVal.consolidate()!.matrix;
  assert(restored.e === pos.x && restored.f === pos.y, 'Undo не восстановил исходное положение');
  toggle!.click(); await pause(); assert(toggle!.getAttribute('aria-pressed') === 'false', 'Привязка не выключается');
  send(task, 'pointerdown', p); send(task, 'pointermove', end); await pause(); send(task, 'pointerup', end); await pause();
  const free = task.transform.baseVal.consolidate()!.matrix;
  assert(Math.abs(free.e - (pos.x + 23)) < 0.01 && Math.abs(free.f - (pos.y + 19)) < 0.01, 'При выключенной привязке движение не свободное');
  toggle!.click(); await pause();
  const create = Array.from(doc.querySelectorAll<HTMLButtonElement>('.diagram-tool')).find(el => el.textContent?.trim() === 'Задача')!;
  create.click(); await pause();
  const place = world(700, 400); send(svg,'pointermove',place); await pause();
  const preview = doc.querySelector<SVGGElement>('[data-placement-preview="task"]')!;
  const previewPosition = preview.getAttribute('transform');
  assert(previewPosition, 'Нет предпросмотра размещения');
  send(svg,'pointerdown',place); await pause();
  assert([...doc.querySelectorAll('[data-diagram-node]')].some(node => node.getAttribute('transform') === previewPosition), 'Созданный объект не совпадает с предпросмотром');
  result.textContent = 'Успешно: сетка в координатах модели, перемещение, отключение привязки и Undo.'; result.dataset.status = 'passed';
} catch (e) { result.textContent = `Ошибка: ${e instanceof Error ? e.message : String(e)}`; result.dataset.status = 'failed'; }
export {};
