const result = document.querySelector<HTMLElement>('#result')!;
const pause = () => new Promise(resolve => setTimeout(resolve, 150));
const assert = (v: unknown, message: string) => { if (!v) throw new Error(message); };
const frame = document.createElement('iframe'); frame.style.cssText = 'width:1000px;height:700px'; document.body.append(frame);
try {
  frame.src = '/tests/editor.html'; await new Promise<void>(resolve => { frame.onload = () => resolve(); }); await pause();
  const win = frame.contentWindow! as Window & typeof globalThis, doc = win.document;
  const svg = doc.querySelector<SVGSVGElement>('.diagram-surface')!;
  const world = (x: number, y: number) => { const p = svg.createSVGPoint(); p.x = x; p.y = y; return p.matrixTransform(svg.getScreenCTM()!); };
  const send = (el: Element, type: string, p: {x:number;y:number}) => el.dispatchEvent(new win.PointerEvent(type, { bubbles:true, button:0, buttons:type === 'pointerup' ? 0 : 1, pointerId:8, clientX:p.x, clientY:p.y }));
  const task = doc.querySelector<SVGGElement>('[data-diagram-node][aria-label*="Проверить заявку"]')!;
  task.setPointerCapture = () => {}; task.hasPointerCapture = () => false;
  const start = task.transform.baseVal.consolidate()!.matrix, original = { x:start.e, y:start.f };
  const point = world(original.x + 30, original.y + 30), end = world(original.x + 50, original.y + 46);
  send(task, 'pointerdown', point); send(task, 'pointermove', end); await pause();
  const guide = doc.querySelector('[data-alignment-guide="alignment"]');
  assert(guide, 'Нет направляющей при сближении с другим объектом');
  assert(task.transform.baseVal.consolidate()!.matrix.f === 162, 'Нет выравнивания по объекту или сетка имеет ошибочный приоритет');
  send(task, 'pointerup', end); await pause();
  assert(!doc.querySelector('[data-alignment-guide]'), 'Направляющая осталась после завершения');
  win.dispatchEvent(new win.KeyboardEvent('keydown', { key:'z', code:'KeyZ', metaKey:true, bubbles:true })); await pause();
  assert(task.transform.baseVal.consolidate()!.matrix.f === original.y, 'Undo не восстановил положение');
  const toggle = doc.querySelector<HTMLButtonElement>('[aria-label="Умные направляющие"]')!; toggle.click(); await pause();
  send(task, 'pointerdown', point); send(task, 'pointermove', end); await pause();
  assert(!doc.querySelector('[data-alignment-guide]'), 'Направляющие не отключились');
  assert(task.transform.baseVal.consolidate()!.matrix.f % 8 === 0, 'При отключенных направляющих не работает сетка');
  send(task, 'pointerup', end); await pause();
  frame.src = '/tests/alignment-editor.html'; await new Promise<void>(resolve => { frame.onload = () => resolve(); }); await pause();
  const spacingWin = frame.contentWindow! as Window & typeof globalThis, spacingDoc = spacingWin.document;
  const surface = spacingDoc.querySelector<SVGSVGElement>('.diagram-surface')!;
  const nodes = [...spacingDoc.querySelectorAll<SVGGElement>('[data-diagram-node]')];
  const third = nodes.find(node => node.transform.baseVal.consolidate()!.matrix.e === 540)!;
  third.setPointerCapture = () => {}; third.hasPointerCapture = () => false;
  const toClient = (x:number, y:number) => { const p = surface.createSVGPoint(); p.x=x; p.y=y; return p.matrixTransform(surface.getScreenCTM()!); };
  const event = (type:string, x:number, y:number) => { const p = toClient(x,y); third.dispatchEvent(new spacingWin.PointerEvent(type,{bubbles:true,pointerId:12,button:0,buttons:type === 'pointerup' ? 0 : 1,clientX:p.x,clientY:p.y})); };
  event('pointerdown',570,150); event('pointermove',531,150); await pause();
  assert(third.transform.baseVal.consolidate()!.matrix.e === 500, 'Не выровнен равный интервал между тремя объектами');
  assert(spacingDoc.querySelectorAll('[data-alignment-guide="spacing"]').length === 2, 'Нет двух подсказок равных интервалов');
  event('pointerup',531,150); await pause();
  result.textContent = 'Успешно: направляющие, приоритет над сеткой, отключение и Undo (синтетические события).'; result.dataset.status = 'passed';
} catch(e) { result.textContent = `Ошибка: ${e instanceof Error ? e.message : String(e)}`; result.dataset.status = 'failed'; }
export {};
