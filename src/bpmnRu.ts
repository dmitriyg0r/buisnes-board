export default function translate(template: string, replacements?: Record<string, string>): string {
  const t = dict[template] ?? template;
  return t.replace(/{([^}]+)}/g, (_, key: string) => {
    const v = replacements?.[key];
    return v === undefined ? `{${key}}` : (dict[v] ?? v);
  });
}

